#!/usr/bin/env python3

first_num = input("Enter the first number: ")
second_num = input("Enter the second number: ")
print("Thanks for the numbers! Here are some calculations:")
print(f"{first_num} + {second_num} = {int(first_num) + int(second_num)}")
print(f"{first_num} - {second_num} = {int(first_num) - int(second_num)}")
print(f"{first_num} * {second_num} = {int(first_num) * int(second_num)}")
print(f"{first_num} / {second_num} = {int(first_num) / int(second_num)}")